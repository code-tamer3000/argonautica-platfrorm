// Раньше — общие константы/хелперы для рантайм-кэша картинок в service worker
// (второй эшелон поверх обычного HTTP-кэша). Слой убран из sw.ts: дважды за
// один день оказался источником реальных поломок на iOS (залипание неудачного
// ответа навсегда, зависание запроса на «холодном» старте PWA). Обычный
// браузерный HTTP-кэш и так покрывает картинки — с ARG-75 presigned-URL
// стабилен весь день (`PRESIGN_GET_WINDOW`, services/media.py), поэтому ключ
// (полный URL) совпадает при повторной отдаче без нашего вмешательства.
//
// `MEDIA_CACHE_NAME`/`clearMediaCache` остаются: на логауте нужно снести уже
// накопленные у пользователей старые записи (устройство может быть общим,
// картинки приватные) — само наполнение кэша больше не идёт, но что уже
// лежит на телефонах, само не исчезнет.

/** Имя кэша в Cache Storage, которым раньше писал рантайм-кэш картинок в sw.ts. */
export const MEDIA_CACHE_NAME = 'arg-media-v2'

/**
 * Снести кэш медиа (логаут: устройство может быть общим, картинки приватные).
 * Best-effort: без Cache API / в приватном режиме просто ничего не делаем —
 * логаут не должен падать из-за кэша.
 */
export async function clearMediaCache(): Promise<void> {
  try {
    if (typeof caches === 'undefined') return
    await caches.delete(MEDIA_CACHE_NAME)
  } catch {
    // no-op
  }
}
